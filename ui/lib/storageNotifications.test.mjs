import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { refreshNotificationDigest, readNotifications, notificationView, markNotification } from './notifications.mjs';
import { readPublicStoragePressure } from './scanHealth.mjs';
import { buildHomeSummary } from './homeSummary.mjs';
import { RUN_STORAGE_WARNING_BYTES, RUN_STORAGE_MAXIMUM_BYTES } from './runRetention.mjs';
test('real storage warnings reach summary and a deduplicated private-safe delivery episode', (t) => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'scout-storage-notification-'));
  t.after(() => fs.rmSync(root, { recursive: true, force: true }));
  const directory = path.join(root, '.scout/scan-input');
  fs.mkdirSync(directory, { recursive: true });
  const file = path.join(directory, 'synthetic-diagnostic.json');
  const resize = (bytes) => { const fd = fs.openSync(file, 'w'); try { fs.ftruncateSync(fd, bytes); } finally { fs.closeSync(fd); } };
  resize(RUN_STORAGE_WARNING_BYTES.artifacts);
  const first = refreshNotificationDigest(root, { mode: 'background' });
  const warning = first.alerts.find((item) => item.kind === 'storage');
  assert.ok(warning, 'storage pressure must create a notification before scans block');
  assert.match(warning.body, /scout cleanup --plan/);
  refreshNotificationDigest(root, { mode: 'background' });
  assert.equal(notificationView(readNotifications(root)).alerts.filter((item) => item.kind === 'storage').length, 1);
  const summary = buildHomeSummary({ scanHealth: { storagePressure: readPublicStoragePressure(root), raw: root }, notifications: first });
  assert.equal(summary.storagePressure.state, 'warning');
  assert.deepEqual(summary.storagePressure.warnings, [{ area: 'artifacts', level: 'warning' }]);
  assert.equal(summary.pendingAlerts[0].kind, 'storage');
  assert.equal(JSON.stringify(summary).includes(root), false);
  resize(0);
  refreshNotificationDigest(root, { mode: 'background' });
  resize(RUN_STORAGE_MAXIMUM_BYTES.artifacts);
  refreshNotificationDigest(root, { mode: 'background' });
  const next = notificationView(readNotifications(root)).alerts.filter((item) => item.kind === 'storage');
  assert.equal(next.length, 2, 'recovered storage followed by renewed pressure creates one new episode');
  markNotification(root, next[0].id, 'delivered');
  assert.equal(notificationView(readNotifications(root)).outbox.filter((item) => item.kind === 'storage').length, 1);
  assert.equal(buildHomeSummary({ scanHealth: { storagePressure: readPublicStoragePressure(root) } }).storagePressure.state, 'blocked');
});
